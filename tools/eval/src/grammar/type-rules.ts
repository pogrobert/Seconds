// Type layer of the design-rules proof (docs/m0/12-design-rules.md, round 2 in 13). Eight type
// systems, each a distinct voice built from OFL fonts that generators rarely reach for. Each sets
// every type role a composition can use (display, statement, body, label, button) as CSS custom
// properties, so any composition works with any type system. Round 2 drops the italic last word
// and the tracked capitals on every label (both known "AI-made" tells, docs/research/
// 2026-11-16-fine-to-ten.md): only systems whose voice is built on capitals use them.

export type TypeRule = {
  key: string
  label: string
  /** What the decision model reads. Describes the feeling, not the fonts. */
  text: string
  /** Google Fonts css2 query. */
  fonts: string
  /**
   * Width of one display character, in em, for the fitting rule: the widest of eight sample
   * names and phrases set in this system's display style, measured in Chromium (2026-11-16).
   */
  advance: number
  vars: Record<string, string>
}

const sans = 'system-ui, -apple-system, "Segoe UI", Arial, sans-serif'
const serif = 'Georgia, "Times New Roman", serif'

/** Labels in sentence case, quiet: the default. */
const quietLabel = (family: string, size = '14px') => ({
  '--f-l': family,
  '--w-l': '500',
  '--t-l': '0',
  '--c-l': 'none',
  '--size-l': size,
})
/** Labels in spaced capitals, for voices built on capitals. */
const capsLabel = (family: string, size = '12px', tracking = '0.14em', weight = '500') => ({
  '--f-l': family,
  '--w-l': weight,
  '--t-l': tracking,
  '--c-l': 'uppercase',
  '--size-l': size,
})

