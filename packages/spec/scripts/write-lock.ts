// Writes section-types.lock.json: the accepted contract that saved sites depend on.
// Run `pnpm --filter @repo/spec lock` after an approved, additive change to the section types.
import { writeFileSync } from 'node:fs'
import { FIELDS } from '../src/fields.ts'
import { SECTION_TYPES } from '../src/section-types.ts'

const fields = Object.fromEntries(
  Object.entries(FIELDS).map(([k, f]) => [k, { kind: f.kind, writer: f.writer }]),
)
const lock = {
  note: 'Generated by scripts/write-lock.ts. Only additions are allowed.',
  fields,
  sectionTypes: SECTION_TYPES,
}
writeFileSync(
  new URL('../section-types.lock.json', import.meta.url),
  `${JSON.stringify(lock, null, 2)}\n`,
)
console.log('wrote section-types.lock.json')
